def main() -> None:
    entries: list[dict[str, object]] = []
    seen: set[str] = set()
    for category, names in GROUPS.items():
        for name in names:
            if name in seen:
                continue
            seen.add(name)
            entries.append(
                {
                    "canonical": name,
                    "category": category,
                    "aliases": ALIASES.get(name, []),
                    "related": [],
                }
            )
    by_name = {entry["canonical"]: entry for entry in entries}
    for left, right in RELATED:
        if left in by_name and right in by_name:
            by_name[left]["related"].append(right)  # type: ignore[union-attr]
            by_name[right]["related"].append(left)  # type: ignore[union-attr]
    for entry in entries:
        entry["related"] = sorted(set(entry["related"]))  # type: ignore[arg-type]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps({"version": 1, "entries": entries}, indent=2, ensure_ascii=False)
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(entries)} entries to {OUT}")


if __name__ == "__main__":
    main()
